"""Import the licensed weapon sensor from the user-supplied NarrowHUD 1.0.5 zip.

Only needed when refreshing the vendor files, not for regular builds.
"""
from pathlib import Path
import argparse
import hashlib
import json
import zipfile
from lupa.lua51 import LuaRuntime

ROOT = Path(__file__).resolve().parents[1]


def convert(value):
    if hasattr(value, 'items'):
        return {str(k): convert(v) for k, v in value.items()}
    return value


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('archive', type=Path)
    args = p.parse_args()
    with zipfile.ZipFile(args.archive) as z:
        original = z.read('Source/narrowhud.lua')
        license_text = z.read('LICENSE.txt')
    text = original.decode('utf-8')
    lines = text.splitlines(keepends=True)
    # Execute only the two literal data tables, never the mod entry point.
    data, seed = LuaRuntime(unpack_returned_tuples=True).execute(
        text[:text.index('-- NarrowHUD (luka189)')] + '\nreturn DATA, SEED')
    facts = convert(data)
    facts.pop('others', None)
    facts.pop('fieldnames', None)
    facts = {'data': facts, 'seed': convert(seed)}
    facts['bootstrap']=json.loads((ROOT / 'data/weapon_models.json').read_text(encoding='utf-8'))
    (ROOT / 'data/weapon_narrow.json').write_text(
        json.dumps(facts, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    # Keep the proven association/normalisation functions; omit menu, unrelated
    # backpack HUD timers, research renderer and every original draw function.
    sensor = ''.join(lines[650:727])
    sensor += "\nlocal cfg={research=false,fire=1}\nlocal MOUSE_BUTTONS={'left','right','middle','extra_1','extra_2'}\n"
    sensor += ''.join(lines[855:950])  # learned tables, persistence, seeds
    sensor += ''.join(lines[967:2134])
    start = sensor.index('local function my_unit()')
    end = sensor.index('-- Your fire button', start)
    sensor = sensor[:start] + 'local function my_unit() return chef.player_unit() end\n' + sensor[end:]
    sensor = sensor.replace('local BUDGET = 1000', 'local BUDGET = 400')
    sensor = sensor.replace('d.fmode = fire_mode_label(t, w)', 'd.fmode = fire_mode_label(t, w)\n  d.raw_fire_mode = w.fire_mode\n  d.raw_options = w.options')
    sensor = sensor.replace("(tonumber(w.reload_stage) or 0) ~= 0 and d.kind == 'ammo'", "(tonumber(w.reload_stage) or 0) ~= 0")
    # No independent non-ammo backpack widgets are part of this sensor.
    sensor = sensor.replace("local watch = chef.watch and chef.watch({ [AVATAR_RESOURCE] = true }, 2) or nil", '')
    sensor += '\n' + (ROOT / 'src/narrowhud_sensor_tail.lua').read_text(encoding='utf-8')
    source = ('-- Based on NarrowHUD 1.0.5 by luka189. See third_party/narrowhud/LICENSE.txt.\n'
              '-- Generated by tools/import_narrowhud.py; weapon sensor only, independent adapter.\n'
              'return function(chef)\nlocal DATA,SEED=chef.data,chef.seed\n'
              'local M={version="1.0.5"}\nlocal log=chef.log\n' + sensor + '\nreturn M\nend\n')
    (ROOT / 'src/vendor/narrowhud_weapon_105.lua').write_text(source, encoding='utf-8')
    out = ROOT / 'third_party/narrowhud'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'LICENSE.txt').write_bytes(license_text)
    (out / 'ORIGIN.json').write_text(json.dumps({
        'name': 'NarrowHUD', 'version': '1.0.5', 'author': 'luka189',
        'url': 'https://github.com/luka189/NarrowHUD',
        'original_source_sha256': hashlib.sha256(original).hexdigest(),
        'changes': 'Weapon sensor extraction; no menu, original renderer, squad/stratagem or independent backpack HUD; 400 type tests per frame; independent unit adapter and weapon-only update tail.'
    }, indent=2) + '\n', encoding='utf-8')
    print('Imported weapon sensor, data and license.')


if __name__ == '__main__':
    main()
